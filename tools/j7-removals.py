"""List everything a Joomla 6.x tree marks "will be removed in 7.0", as class + member.

usage: python -I j7-removals.py <joomla-root> > JOOMLA7-REMOVALS-6.2.md

Reads each @deprecated docblock that mentions 7.0 and the declaration after it
(class, interface, trait, method, property, constant). Also lists the classes the
compat6 plugin still carries (they go with it). Regenerate it from each new 6.x tree.
"""
import os, re, sys

root = sys.argv[1].rstrip('/\\')
scan = ['libraries/src', 'administrator/components', 'components', 'plugins', 'api/components', 'modules', 'administrator/modules']
decl = re.compile(r'^\s*(?:(?:abstract|final|public|protected|private|static|readonly)\s+)*'
                  r'(class|interface|trait|enum|function|const|\$)\s*&?\s*([A-Za-z_][A-Za-z0-9_]*)')
rows = []

for top in scan:
    base = os.path.join(root, top)
    for dp, _, files in os.walk(base):
        if 'compat6' in dp or 'vendor' in dp:
            continue
        for f in files:
            if not f.endswith('.php'):
                continue
            p = os.path.join(dp, f)
            lines = open(p, encoding='utf-8', errors='replace').read().splitlines()
            ns = next((m.group(1) for l in lines if (m := re.match(r'namespace\s+([^;]+);', l))), '')
            cls = ''
            i = 0
            while i < len(lines):
                l = lines[i]
                m = re.match(r'\s*(?:(?:abstract|final|readonly)\s+)*(class|interface|trait|enum)\s+(\w+)', l)
                if m and not l.strip().startswith('*'):
                    cls = m.group(2)
                if '/**' in l:
                    j = i
                    block = []
                    while j < len(lines) and '*/' not in lines[j]:
                        block.append(lines[j]); j += 1
                    block.append(lines[j] if j < len(lines) else '')
                    # "@property-read Input $input {@deprecated ... 7.0}" deprecates one magic property, not the class.
                    props = [b for b in block if re.search(r'@property', b) and '7.0' in b]
                    block = [b for b in block if b not in props]
                    k = j + 1
                    while k < len(lines) and (not lines[k].strip() or lines[k].strip().startswith('#[')):
                        k += 1
                    owner = decl.match(lines[k]) if k < len(lines) else None
                    for b in props:
                        pm = re.search(r'@property(?:-read|-write)?\s+\S+\s+\$(\w+)\s*(.*)', b)
                        if pm and owner:
                            rows.append(('libraries' if top == 'libraries/src' else top.split('/')[0],
                                         f'{ns}\\{owner.group(2)}::${pm.group(1)} (magic)',
                                         re.sub(r'[{}]|@deprecated', '', pm.group(2)).strip()[:220]))
                    text = ' '.join(b.strip(' */') for b in block)
                    if re.search(r'@deprecated[^@]*\b7\.0', text):
                        k = j + 1
                        while k < len(lines) and (not lines[k].strip() or lines[k].strip().startswith('#[')):
                            k += 1
                        d = decl.match(lines[k]) if k < len(lines) else None
                        why = re.search(r'@deprecated\s+([^@]*)', text).group(1).strip()
                        why = re.sub(r'\s+', ' ', why)[:220]
                        if d:
                            kind, name = d.group(1), d.group(2)
                            if kind in ('class', 'interface', 'trait', 'enum'):
                                what = f'{ns}\\{name}'
                            elif kind == 'function':
                                what = f'{ns}\\{cls}::{name}()'
                            elif kind == 'const':
                                what = f'{ns}\\{cls}::{name}'
                            else:
                                what = f'{ns}\\{cls}::${name}'
                            rows.append((top.split('/')[0] if top != 'libraries/src' else 'libraries', what, why))
                    i = j
                i += 1

ver = open(os.path.join(root, 'libraries/src/Version.php'), encoding='utf-8').read()
v = '.'.join(re.search(rf'{k}_VERSION = (\d+)', ver).group(1) for k in ('MAJOR', 'MINOR', 'PATCH'))
print(f'# Removed in Joomla 7.0, as marked in Joomla {v}\n')
print(f'Generated by `tools/j7-removals.py` from a Joomla {v} tree. {len(rows)} declarations. '
      'Each row is a `@deprecated` annotation that names 7.0; the text is Joomla\'s own, including the replacement when it gives one. '
      'Regenerate from each new 6.x release: Joomla keeps adding to this list.\n')
print('| Where | Declaration | Joomla\'s note |\n|---|---|---|')
for where, what, why in sorted(rows, key=lambda r: r[1]):
    print(f'| {where} | `{what}` | {why.replace("|", "/")} |')

cdir = os.path.join(root, 'plugins/behaviour/compat6')
if os.path.isdir(cdir):
    print('\n## Kept only by the "Behaviour - Backward Compatibility 6" plugin\n')
    print('These exist on Joomla 6 only while compat6 is on, and go when it goes.\n')
    legacy = sorted(os.path.relpath(os.path.join(dp, f), os.path.join(cdir, 'classes')).replace(os.sep, '\\')[:-4]
                    for dp, _, fs in os.walk(os.path.join(cdir, 'classes')) for f in fs if f.endswith('.php'))
    print('**Legacy classes** (option *Legacy classes*, on by default): ' + ', '.join(f'`Joomla\\CMS\\{c}`' for c in legacy) + '\n')
    n = sum(open(os.path.join(cdir, 'src/classmap', f), encoding='utf-8').read().count('registerAlias') for f in os.listdir(os.path.join(cdir, 'src/classmap')))
    print(f'**Class aliases** (option *Class aliases*, off by default): {n} old names (`J*` classes and pre-namespace helpers) in `plugins/behaviour/compat6/src/classmap/`.')
